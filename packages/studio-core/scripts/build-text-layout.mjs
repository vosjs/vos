/**
 * Generate the injectable form of the styled-text layout
 * (`@vosjs/elements` `src/text/layout.ts`): a self-contained IIFE as a string constant,
 * which the studio entry inlines into its program so the page that paints a
 * text layer runs EXACTLY the layout the host picks and edits with. Output
 * is committed; `richTextLayoutCode.test.ts` fails the gates when it is
 * stale.
 *
 *   node packages/studio-core/scripts/build-text-layout.mjs
 *
 * Re-run whenever layout.ts changes and commit the regenerated module.
 */
/* global console */
import { execSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { buildSync } from 'esbuild'

const HERE = dirname(fileURLToPath(import.meta.url))
const SOURCE = join(HERE, '../../elements/src/text/layout.ts')
const OUT_FILE = join(HERE, '../src/richText/layoutCode.ts')

const { outputFiles } = buildSync({
  entryPoints: [SOURCE],
  bundle: true,
  format: 'iife',
  globalName: '__vosTextLayout',
  target: 'es2020',
  minify: true,
  write: false,
})
const code = outputFiles[0].text.trim()
// The code rides inside a function string that the compiler embeds in a
// module: a backtick or a `${` would end or open a template there.
if (code.includes('`') || code.includes('${')) {
  throw new Error('the layout bundle holds a template literal; write it out')
}
const hash = createHash('sha256').update(readFileSync(SOURCE)).digest('hex')

writeFileSync(
  OUT_FILE,
  `// GENERATED by scripts/build-text-layout.mjs from
// @vosjs/elements' text/layout.ts. Do not edit: change layout.ts and re-run
// the script.

/** sha256 of the layout.ts this was generated from (the staleness gate). */
export const TEXT_LAYOUT_SOURCE_HASH =
  '${hash}'

/** An IIFE that declares \`var __vosTextLayout\` (layoutText and friends). */
export const textLayoutCode = ${JSON.stringify(code)}
`,
)
// The gate checks formatting too, so the output is written formatted.
execSync(`pnpm exec prettier --write ${JSON.stringify(OUT_FILE)}`, {
  stdio: 'ignore',
})
console.log(`Built the text layout code (${code.length} bytes) -> ${OUT_FILE}`)
